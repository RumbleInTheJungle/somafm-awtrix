#!/usr/bin/env python3
"""Regenerate the built-in channel table in scripts/somafm.be.

Fetches https://somafm.com/channels.json plus every channel logo, derives a
"signature colour" per channel (the dominant vivid hue of its logo, pushed to
full LED brightness), and rewrites the block between
    # BEGIN CHANNELS ... # END CHANNELS
in scripts/somafm.be.

Usage:
    uv run tools/gen_channels.py            # rewrite the table
    uv run tools/gen_channels.py --dry-run  # print it only
"""
import argparse
import colorsys
import datetime
import io
import json
import pathlib
import re
import sys
import urllib.request

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIB = ROOT / "scripts" / "somafm.be"
CHANNELS_URL = "https://somafm.com/channels.json"
# Identifies this project to SomaFM, at their request. If you fork this code,
# change it to your own project and get your own permission (see NOTICE.md).
UA = {"User-Agent": "somafm-awtrix-tools/2.0(+https://github.com/RumbleInTheJungle/somafm-awtrix)"}

GREY = 0xB4B4B4  # channels whose logo has no vivid colour

# Hand-picked colours where the automatic pick is ambiguous or collides
# with another popular channel. Keys are channel ids, values 0xRRGGBB.
OVERRIDES = {
    "secretagent": 0xFF6A00,  # logo red collides with metal -> spy orange
    "lush": 0xFF5FA0,         # amber collides with UI accent -> pink
    "indiepop": 0xFFE040,     # amber collides with UI accent -> yellow
    "darkzone": 0x7A3CFF,     # logo picks pale yellow; "dark" reads better as deep violet
}


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=20) as r:
        return r.read()


def signature_colour(img_bytes: bytes) -> int:
    im = Image.open(io.BytesIO(img_bytes)).convert("RGB").resize((24, 24), Image.LANCZOS)
    pixels = im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()
    bins: dict[int, list[tuple[float, float, float]]] = {}
    for p in pixels:
        h, s, v = colorsys.rgb_to_hsv(*(c / 255 for c in p))
        if s > 0.35 and v > 0.3:
            bins.setdefault(int(h * 12) % 12, []).append((h, s, v))
    if not bins:
        return GREY
    best = max(bins, key=lambda k: sum(s * v for _, s, v in bins[k]))
    hsv = bins[best]
    # average hue on the circle to avoid red wrap-around artefacts
    import math
    x = sum(math.cos(2 * math.pi * h) for h, _, _ in hsv)
    y = sum(math.sin(2 * math.pi * h) for h, _, _ in hsv)
    hue = (math.atan2(y, x) / (2 * math.pi)) % 1.0
    sat = min(1.0, max(0.6, sum(s for _, s, _ in hsv) / len(hsv) * 1.15))
    r, g, b = colorsys.hsv_to_rgb(hue, sat, 1.0)
    return (int(r * 255) << 16) | (int(g * 255) << 8) | int(b * 255)


def berry_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    channels = json.loads(fetch(CHANNELS_URL))["channels"]
    rows = []
    for c in channels:
        cid = c["id"]
        if not any(p.get("format") == "mp3" for p in c.get("playlists", [])):
            print(f"skip {cid}: no MP3 stream", file=sys.stderr)
            continue
        if cid in OVERRIDES:
            colour = OVERRIDES[cid]
        else:
            try:
                colour = signature_colour(fetch(c["image"]))
            except Exception as e:  # logo missing or unreadable
                print(f"warn {cid}: {e}", file=sys.stderr)
                colour = GREY
        genre = c.get("genre", "").split("|")[0]
        rows.append((cid, c["title"], genre, colour))
        print(f"{cid:16} {colour:06X}  {c['title']}", file=sys.stderr)

    stamp = datetime.date.today().isoformat()
    lines = [
        "# BEGIN CHANNELS",
        f"# Generated by tools/gen_channels.py on {stamp} ({len(rows)} channels). Do not edit by hand.",
        "# [id, title, genre, signature colour]",
        "sf.CHANNELS = [",
    ]
    for cid, title, genre, colour in rows:
        lines.append(f"  [{berry_str(cid)}, {berry_str(title)}, {berry_str(genre)}, 0x{colour:06X}],")
    lines += ["]", "# END CHANNELS"]
    block = "\n".join(lines)

    if args.dry_run:
        print(block)
        return 0
    src = LIB.read_text(encoding="utf-8")
    new, n = re.subn(r"# BEGIN CHANNELS.*?# END CHANNELS", lambda _: block, src, flags=re.S)
    if n != 1:
        print("marker block not found in " + str(LIB), file=sys.stderr)
        return 1
    LIB.write_text(new, encoding="utf-8")
    print(f"wrote {len(rows)} channels to {LIB.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
